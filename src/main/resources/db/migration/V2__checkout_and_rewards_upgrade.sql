-- Existing installations are baselined at V1; add new fields without removing records.
alter table usuarios add column if not exists tema_passe varchar(255);
alter table pedidos add column if not exists checkout_key varchar(100);
alter table pedidos add column if not exists temporada_passe_id bigint;
create unique index if not exists uq_pedidos_checkout_key on pedidos(checkout_key);
alter table pagamentos add column if not exists checkout_url varchar(2048);
alter table passe_xp_historico add column if not exists estornado boolean not null default false;
alter table passe_recompensa_resgates add column if not exists codigo_entrega varchar(60);
alter table passe_recompensa_resgates add column if not exists pedido_utilizado_id bigint references pedidos(id);
create unique index if not exists uq_resgate_codigo_entrega on passe_recompensa_resgates(codigo_entrega);
create table if not exists passe_eventos (
 id bigint generated by default as identity primary key,
 usuario_id bigint not null references usuarios(id),
 dia date not null,
 acao varchar(255) not null,
 referencia varchar(100) not null,
 unique(usuario_id,dia,acao,referencia)
);
