create table eventos_semanais (
  id bigint generated by default as identity primary key,
  titulo varchar(100) not null,
  descricao varchar(500) not null,
  inicio timestamp not null,
  fim timestamp not null,
  multiplicador integer not null check (multiplicador between 1 and 5),
  limite_xp integer not null check (limite_xp > 0),
  meta_xp integer not null check (meta_xp between 1 and limite_xp),
  minimo_compra numeric(10,2) not null check (minimo_compra >= 0),
  selo varchar(80) not null,
  check (fim > inicio)
);
create table evento_resgates (
  id bigint generated by default as identity primary key,
  evento_id bigint not null references eventos_semanais(id),
  usuario_id bigint not null references usuarios(id),
  resgatado_em timestamp not null,
  unique (evento_id, usuario_id)
);
create table notificacoes (
  id bigint generated by default as identity primary key,
  usuario_id bigint not null references usuarios(id),
  titulo varchar(140) not null,
  mensagem varchar(300) not null,
  destino varchar(120) not null,
  criado_em timestamp not null,
  lida boolean not null
);
create index idx_notificacoes_usuario on notificacoes (usuario_id, id desc);
create table recuperacao_senha (
  usuario_id bigint primary key references usuarios(id),
  hash varchar(64) not null unique,
  expira_em timestamp not null
);
